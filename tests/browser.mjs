import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { mkdtemp, mkdir, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const extension = resolve('extension');
const profile = await mkdtemp(resolve(tmpdir(), 'haezoom-ui-'));
const output = process.env.UI_OUTPUT || resolve('docs/screenshots');
await mkdir(output, { recursive: true });
const context = await chromium.launchPersistentContext(profile, { headless: true, channel: 'chromium', args: [`--disable-extensions-except=${extension}`, `--load-extension=${extension}`], viewport: { width: 1440, height: 1050 } });
try {
  const worker = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
  const extensionId = new URL(worker.url()).host;
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`chrome-extension://${extensionId}/workspace.html`);
  await page.getByRole('button', { name: '서버 없이 샘플 결과 둘러보기' }).click();
  await page.screenshot({ path: resolve(output, '01-document.png'), fullPage: true });
  await page.getByRole('button', { name: '할 일 화면으로 가져가기 (미리보기)' }).click();
  assert.equal(await page.locator('#task-list .task-card').count(), 2);
  const first = page.locator('#task-list .task-card').first();
  await first.getByRole('button', { name: '날짜·내용 확인' }).click();
  await first.getByLabel('확인한 날짜').fill('2026-11-13');
  await first.getByRole('checkbox').check();
  await first.getByRole('button', { name: '화면에 반영' }).click();
  assert.match(await first.innerText(), /확인 완료/);
  await first.getByRole('button', { name: '완료 표시' }).click();
  await page.locator('#filter').selectOption('completed');
  assert.equal(await page.locator('#task-list .task-card').count(), 1);
  await page.locator('#filter').selectOption('all');
  await page.screenshot({ path: resolve(output, '02-tasks.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: resolve(output, '03-mobile.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.reload();
  assert.equal(await page.locator('#task-list .task-card').count(), 0);
  const newTab = context.waitForEvent('page');
  const response = await page.evaluate(() => chrome.runtime.sendMessage({ type: 'selection', payload: { text: '신청서를 다음 주 금요일까지 제출해 주세요.', source: { title: '테스트 공지' } } }));
  assert.equal(response.ok, true);
  const draftPage = await newTab; await draftPage.waitForLoadState();
  assert.match(await draftPage.locator('#input-text').inputValue(), /신청서/);
  assert.equal(await draftPage.evaluate(async () => (await chrome.storage.session.get('pendingSelection')).pendingSelection), undefined);
  const popup = await context.newPage(); await popup.goto(`chrome-extension://${extensionId}/popup.html`);
  await popup.setViewportSize({ width: 390, height: 780 });
  await popup.screenshot({ path: resolve(output, '04-popup.png'), fullPage: true });
  const selectionPage = await context.newPage();
  await selectionPage.route('https://school.example/**', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><html lang="ko"><meta charset="utf-8"><title>학교 공지</title><body style="font:20px sans-serif;padding:80px;line-height:2"><h1>현장체험학습 안내</h1><p id="notice">2026년 11월 12일까지 참가 신청서를 담임 선생님께 제출해 주세요. 참가비는 15,000원입니다.</p><textarea aria-label="입력창">비공개 입력 중인 내용</textarea></body></html>' }));
  await selectionPage.goto('https://school.example/notice');
  await selectionPage.evaluate(() => { globalThis.chrome = { runtime: { sendMessage: async message => { globalThis.lastMessage = message; return { ok: true }; }, onMessage: { addListener() {}, removeListener() {} } } }; });
  await selectionPage.addScriptTag({ content: await readFile(resolve(extension, 'selection-helper.js'), 'utf8') });
  const cdp = await context.newCDPSession(selectionPage);
  const buttonByName = async name => {
    const { nodes } = await cdp.send('Accessibility.getFullAXTree');
    return nodes.find(entry => entry.role?.value === 'button' && entry.name?.value === name && !entry.ignored);
  };
  const clickClosedButton = async name => {
    const button = await buttonByName(name); assert.ok(button, `button present: ${name}`);
    const { model } = await cdp.send('DOM.getBoxModel', { backendNodeId: button.backendDOMNodeId });
    await selectionPage.mouse.click((model.content[0] + model.content[4]) / 2, (model.content[1] + model.content[5]) / 2);
  };
  assert.ok(await buttonByName('해줌 도우미 열기'));
  await clickClosedButton('해줌 도우미 열기');
  assert.ok(await buttonByName('선택한 내용 가져오기 →'));
  assert.equal(await selectionPage.evaluate(() => globalThis.lastMessage), undefined);
  await selectionPage.screenshot({ path: resolve(output, '06-floating-menu.png'), fullPage: true });
  await clickClosedButton('내 할 일 둘러보기 ↗');
  assert.deepEqual(await selectionPage.evaluate(() => globalThis.lastMessage), { type: 'openWorkspace', payload: { view: 'tasks' } });
  await selectionPage.evaluate(() => { delete globalThis.lastMessage; });
  await selectionPage.locator('#notice').click();
  await selectionPage.evaluate(() => { const range = document.createRange(); range.selectNodeContents(document.getElementById('notice')); const selection = getSelection(); selection.removeAllRanges(); selection.addRange(range); document.dispatchEvent(new PointerEvent('pointerup')); });
  const host = selectionPage.locator('[data-haezoom-helper]'); await host.waitFor({ state: 'visible' });
  assert.equal(await selectionPage.evaluate(() => globalThis.lastMessage), undefined);
  await selectionPage.screenshot({ path: resolve(output, '05-selection.png'), fullPage: true });
  const box = await host.boundingBox();
  await selectionPage.mouse.click(box.x + 70, box.y + 20);
  await host.waitFor({ state: 'hidden' });
  assert.match(await selectionPage.evaluate(() => globalThis.lastMessage.payload.text), /참가 신청서/);
  await selectionPage.locator('textarea').focus();
  await selectionPage.locator('textarea').selectText();
  await selectionPage.waitForTimeout(250);
  assert.equal(await host.isVisible(), false);
  await clickClosedButton('해줌 도우미 열기');
  await selectionPage.keyboard.press('Escape');
  assert.equal(await buttonByName('내 할 일 둘러보기 ↗'), undefined);
  await clickClosedButton('해줌 도우미 열기');
  await clickClosedButton('이 페이지에서 버튼 숨기기');
  assert.equal(await selectionPage.locator('[data-haezoom-launcher]').isVisible(), false);
  assert.deepEqual(errors, []);
  console.log('PASS: real unpacked extension load, samples, edit/confirm/complete/filter, responsive layout, reset, background selection handoff; helper DOM test (mock runtime): selection chip, no auto-send, click, private input exclusion.');
} finally { await context.close(); }
